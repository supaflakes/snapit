  const LANGUAGES = [['fr', 'Français'], ['en', 'English']];

  function resolve(language, systemLocale) {
    if (STRINGS[language]) return language;
    return String(systemLocale || '').toLowerCase().startsWith('fr') ? 'fr' : 'en';
  }

  function t(lang, key, params) {
    let text = STRINGS[lang]?.[key] ?? STRINGS.fr[key] ?? key;
    if (params) for (const [name, value] of Object.entries(params)) text = text.split(`{${name}}`).join(value);
    return text;
  }

  // « Shift+PrintScreen » → « Maj+Impr. écran »
  function formatAccelerator(lang, accelerator) {
    if (!accelerator) return '';
    return accelerator
      .split('+')
      .map((part) => (STRINGS[lang]?.[`key.${part}`] ? t(lang, `key.${part}`) : part))
      .join('+');
  }

  const I18N = { STRINGS, LANGUAGES, resolve, t, formatAccelerator };
  if (typeof module !== 'undefined' && module.exports) module.exports = I18N;
  else root.I18N = I18N;
